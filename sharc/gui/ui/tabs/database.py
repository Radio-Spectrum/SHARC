"""Database tab: base-station database, subsets and real terrain.

Everything here maps one-to-one to the engine's `database` block
(`sharc/parameters/database/parameters_database.py`). The YAML is generated by
`core/yaml_builder.py::_database_block`; the file is inspected with pandas so the
user sees immediately whether the required columns exist.
"""
from __future__ import annotations

import os
from typing import Dict

from PySide6.QtCore import QTimer, Qt
from PySide6.QtWidgets import (
    QCheckBox, QComboBox, QFileDialog, QFrame, QGridLayout, QGroupBox, QHBoxLayout,
    QLabel, QLineEdit, QPushButton, QScrollArea, QVBoxLayout, QWidget,
)

from core.state import SharcVar

# Engine constants (kept in sync with parameters_database.py; checked by tests).
TOPOLOGY_COLUMNS = ("latitude", "longitude", "azimute", "altura")
ANTENNA_COLUMNS = ("n_rows", "n_columns", "beamforming_gain", "element_max_g",
                   "tx_power", "sub_num_rows", "downtilt")

DEFAULTS: Dict[str, object] = {
    "db_enabled": False,
    "db_file": "",
    "db_delimiter": ",",
    "db_num_subsets": 1,
    "db_from_sites": False,
    "db_from_antenna": False,
    "db_use_terrain": False,
    "db_terrain_ref_gpkg": "",
    "db_terrain_resolution": 100.0,
    "db_terrain_urban": 30,
    "db_terrain_suburban": 150,
    "db_terrain_rural": 500,
    "db_terrain_water": "exclude",
    "db_terrain_output_dir": "",
}


class DatabaseStateManager:
    """Variables of the Database tab (same `.get(key)` API as the other tab states)."""

    def __init__(self):
        self.vars: Dict[str, SharcVar] = {}
        for key, value in DEFAULTS.items():
            self.vars[key] = SharcVar(value, bool if isinstance(value, bool) else str)

    def get(self, key: str) -> SharcVar:
        if key not in self.vars:
            self.vars[key] = SharcVar("")
        return self.vars[key]


def inspect_database(path: str, delimiter: str) -> Dict[str, object]:
    """Read the database header/rows with pandas and summarise it (no engine needed)."""
    import pandas as pd
    info: Dict[str, object] = {"ok": False, "message": ""}
    if not path or not os.path.isfile(path):
        info["message"] = "File not found."
        return info
    try:
        if path.lower().endswith(".xlsx"):
            df = pd.read_excel(path)
        else:
            df = pd.read_csv(path, sep=delimiter)
    except Exception as exc:  # noqa: BLE001
        info["message"] = f"Could not read the file: {exc}"
        return info
    cols = [str(c) for c in df.columns]
    info.update(
        ok=True, rows=len(df), columns=cols,
        missing_sites=[c for c in TOPOLOGY_COLUMNS if c not in cols],
        missing_antenna=[c for c in ANTENNA_COLUMNS if c not in cols],
    )
    if "latitude" in cols and "longitude" in cols and len(df):
        info["bbox"] = (float(df["longitude"].min()), float(df["latitude"].min()),
                        float(df["longitude"].max()), float(df["latitude"].max()))
    return info


class DatabaseTab(QWidget):
    """Base-station database configuration page."""

    def __init__(self, app, parent_frame=None):
        super().__init__(parent_frame)
        self.app = app
        self.state = DatabaseStateManager()
        self._info: Dict[str, object] = {}
        self._build_ui()
        self._timer = QTimer(self)
        self._timer.setSingleShot(True)
        self._timer.setInterval(300)
        self._timer.timeout.connect(self.refresh_info)
        self.state.get("db_file").value_changed.connect(lambda *_: self._timer.start())
        self.state.get("db_delimiter").value_changed.connect(lambda *_: self._timer.start())
        self.state.get("db_from_sites").value_changed.connect(self._on_sites_toggled)
        self.refresh_info()

    # ------------------------------------------------------------------ UI
    def _field(self, key: str, widget=None, choices=None):
        var = self.state.get(key)
        if isinstance(DEFAULTS.get(key), bool):
            w = QCheckBox()
            w.setChecked(bool(var.get()))
            w.toggled.connect(var.set)
            var.value_changed.connect(lambda v, w=w: w.setChecked(bool(v)) if w.isChecked() != bool(v) else None)
            return w
        if choices:
            w = QComboBox()
            w.addItems([str(c) for c in choices])
            w.setCurrentText(str(var.get()))
            w.currentTextChanged.connect(var.set)
            var.value_changed.connect(lambda v, w=w: w.setCurrentText(str(v)))
            return w
        w = widget or QLineEdit()
        w.setText(str(var.get()))
        w.textChanged.connect(var.set)
        var.value_changed.connect(lambda v, w=w: w.setText(str(v)) if w.text() != str(v) else None)
        return w

    def _build_ui(self):
        outer = QVBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.NoFrame)
        inner = QWidget()
        lay = QVBoxLayout(inner)
        scroll.setWidget(inner)
        outer.addWidget(scroll)

        # --- Base-station database -------------------------------------
        g1 = QGroupBox("Base-Station Database")
        grid = QGridLayout(g1)
        grid.addWidget(QLabel("Use database"), 0, 0)
        grid.addWidget(self._field("db_enabled"), 0, 1)
        grid.addWidget(QLabel("Database file"), 1, 0)
        file_row = QHBoxLayout()
        file_row.addWidget(self._field("db_file"))
        btn = QPushButton("Browse")
        btn.clicked.connect(self._browse)
        file_row.addWidget(btn)
        grid.addLayout(file_row, 1, 1)
        grid.addWidget(QLabel("Delimiter (csv)"), 2, 0)
        grid.addWidget(self._field("db_delimiter", choices=[",", "\t", "|"]), 2, 1)
        grid.addWidget(QLabel("Number of subsets"), 3, 0)
        grid.addWidget(self._field("db_num_subsets"), 3, 1)
        grid.addWidget(QLabel("Take sites from database"), 4, 0)
        grid.addWidget(self._field("db_from_sites"), 4, 1)
        grid.addWidget(QLabel("Take antenna parameters from database"), 5, 0)
        grid.addWidget(self._field("db_from_antenna"), 5, 1)
        lay.addWidget(g1)

        # --- Database contents --------------------------------------------
        g2 = QGroupBox("Database Contents")
        v = QVBoxLayout(g2)
        self.lbl_info = QLabel("")
        self.lbl_info.setWordWrap(True)
        self.lbl_info.setTextInteractionFlags(Qt.TextSelectableByMouse)
        v.addWidget(self.lbl_info)
        lay.addWidget(g2)

        # --- Real terrain -----------------------------------------------------
        g3 = QGroupBox("Real Terrain")
        t = QGridLayout(g3)
        rows = [
            ("Use real terrain", self._field("db_use_terrain")),
            ("Adaptive mesh file (.gpkg) [optional]", self._field("db_terrain_ref_gpkg")),
            ("Terrain/land-cover grid resolution [m]", self._field("db_terrain_resolution")),
            ("Mesh resolution, urban [m]", self._field("db_terrain_urban")),
            ("Mesh resolution, suburban [m]", self._field("db_terrain_suburban")),
            ("Mesh resolution, rural [m]", self._field("db_terrain_rural")),
            ("Water in mesh", self._field("db_terrain_water", choices=["exclude", "coarse"])),
            ("Terrain cache folder", self._field("db_terrain_output_dir")),
        ]
        for i, (label, w) in enumerate(rows):
            t.addWidget(QLabel(label), i, 0)
            t.addWidget(w, i, 1)
        lay.addWidget(g3)
        lay.addStretch(1)

    # ------------------------------------------------------------- actions
    def _browse(self):
        path, _ = QFileDialog.getOpenFileName(
            self, "Select base-station database", "", "Databases (*.csv *.xlsx);;All files (*)")
        if path:
            self.state.get("db_file").set(path)
            self.state.get("db_enabled").set(True)

    def _on_sites_toggled(self, on):
        """Sites from the database need the MACRO_COUNTRIES topology in the engine."""
        if on in (True, "True", "true", 1):
            try:
                self.app.tab_imt.state.get("topo_type").set("Macro_countries")
            except AttributeError:
                pass
            self.center_scenario_on_database()

    def center_scenario_on_database(self):
        """Put the IMT reference (local frame origin) at the centre of the database sites."""
        info = self._info if self._info.get("ok") else inspect_database(
            str(self.state.get("db_file").get() or ""), str(self.state.get("db_delimiter").get() or ","))
        bbox = info.get("bbox") if info.get("ok") else None
        if not bbox:
            return
        w, s_, e, n = bbox
        st = self.app.tab_imt.state
        st.get("topo_c_lat").set(round((s_ + n) / 2.0, 4))
        st.get("topo_c_lon").set(round((w + e) / 2.0, 4))

    def refresh_info(self):
        path = str(self.state.get("db_file").get() or "").strip()
        if not path:
            self._info = {"ok": False, "message": "No database selected."}
            self.lbl_info.setText("No database selected.")
            return
        info = inspect_database(path, str(self.state.get("db_delimiter").get() or ","))
        self._info = info
        if not info["ok"]:
            self.lbl_info.setText(str(info["message"]))
            return
        lines = [f"{info['rows']} rows, {len(info['columns'])} columns"]
        if "bbox" in info:
            w, s, e, n = info["bbox"]
            lines.append(f"Extent: lon {w:.3f} to {e:.3f}, lat {s:.3f} to {n:.3f}")
        if info["missing_sites"]:
            lines.append("Missing columns for sites: " + ", ".join(info["missing_sites"]))
        else:
            lines.append("Site columns: OK (latitude, longitude, azimute, altura)")
        if info["missing_antenna"]:
            lines.append("Missing columns for antenna parameters: " + ", ".join(info["missing_antenna"]))
        else:
            lines.append("Antenna columns: OK")
        self.lbl_info.setText("\n".join(lines))

    # ---------------------------------------------------------------- YAML
    def to_yaml(self) -> dict:
        """The engine's `database` block, or {} when the database is disabled."""
        from core.yaml_builder import _as_bool, _num_or_str
        g = lambda k: self.state.get(k).get()  # noqa: E731
        if not _as_bool(g("db_enabled")):
            return {}
        path = str(g("db_file") or "").strip()
        out_dir = str(g("db_terrain_output_dir") or "").strip()
        if not out_dir:
            from core.run_service import run_root
            out_dir = str(run_root().parent / "terrain_cache")
        block = {
            "database_file_name": os.path.abspath(path) if path else None,
            "delimiter": str(g("db_delimiter") or ","),
            "num_subsets": int(_num_or_str(g("db_num_subsets")) or 1),
            "from_db_topology_countries": _as_bool(g("db_from_sites")),
            "from_db_antenna_params": _as_bool(g("db_from_antenna")),
            "use_real_terrain": _as_bool(g("db_use_terrain")),
            "terrain": {
                "ref_gpkg": os.path.abspath(g("db_terrain_ref_gpkg")) if str(g("db_terrain_ref_gpkg")).strip() else "",
                "mesh_resolution_m": float(_num_or_str(g("db_terrain_resolution")) or 100.0),
                "mesh_urban_res_m": int(float(_num_or_str(g("db_terrain_urban")) or 30)),
                "mesh_suburban_res_m": int(float(_num_or_str(g("db_terrain_suburban")) or 150)),
                "mesh_rural_res_m": int(float(_num_or_str(g("db_terrain_rural")) or 500)),
                "mesh_water": str(g("db_terrain_water") or "exclude"),
                "mesh_output_dir": out_dir,
            },
        }
        return block
